def N_(text: str) -> str:  # noqa: N802 - convenção gettext
    """Marca um texto para tradução sem traduzir agora (constantes de módulo)."""
    return text


def set_language(lang: str) -> None:
    global _language
    if lang not in SUPPORTED:
        raise ValueError(f"unsupported language: {lang}")
    _language = lang


def get_language() -> str:
    return _language


def tr(text: str, **values: object) -> str:
    """Traduz `text` (em PT) para o idioma atual e aplica `str.format(**values)`.

    Sem tradução, usa o original em PT; assim um texto novo nunca quebra a interface.
    """
    template = EN.get(text, text) if _language == "en" else text
    return template.format(**values) if values else template
